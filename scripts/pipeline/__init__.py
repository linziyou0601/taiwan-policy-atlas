"""台灣政策圖譜的資料管線。

把公開的來源依抓取、抽取、主張、配題、評分、發布各階段轉換成選舉的資料集，主題測驗的手寫表由 topics 階段發布，選區地圖由 geo 階段轉出，選舉與主題測驗都列在題組索引。每個階段的步驟與判讀規則見 docs/pipeline/ 與階段同名的文件。

指令：
  `npm run pipeline -- <階段> <工具> [參數]`
  階段與工具列在 `__main__.py` 的 COMMANDS，也可以執行 `npm run pipeline -- --help`。

慣例：
  - 每個階段一個目錄，與 data/ 的階段目錄、docs/pipeline/ 的文件、tests/pipeline/ 的測試同名。
  - 階段目錄裡一個檔案是一支工具，檔名就是子指令。run.py 是這個階段的核對與產物，檔名以底線開頭的模組是工具共用的片段。
  - 每個階段只讀取上一個階段的產物、這個階段的手寫輸入與設定表，產物寫入 data/ 的同名目錄，鍵名使用 snake_case。
  - 來源的 adapter 在 adapters/，一種來源的格式一檔，各階段共用。只有管線讀的設定表在 tables/。
"""
